// ─────────────────────────────────────────────────────────────────────────────
// Location.js  —  Sequelize model for mLocation (Godown Location master)
//
// PURPOSE:
//   A Location is a named spot inside a Godown.
//   Example: Godown "01" may have locations "L1", "L2", "FRONT", "BACK".
//   This helps track exactly WHERE inside a godown a particular lot is stored.
//
// SCOPE: SHARED MASTER (group-level)
//   - All companies in the same group (e.g. BHW group: ADS + TEST) share
//     the same set of locations because they share the same physical godowns.
//   - Only the PRIMARY company can create / edit / delete locations.
//   - After each write, syncToGroup() copies the record to all sibling company
//     databases so every company always has an up-to-date local copy.
//
// PRIMARY KEY:
//   pkLocationID  — UUID v4 generated in Node (randomUUID).
//   Web equivalent of VB6 format: GroupID!SerialNum  e.g. BHW!1
//
// FACTORY PATTERN:
//   This file exports a function defineLocation(db) instead of a static model.
//   Reason: each company lives in its own MySQL database (gms_ads, gms_test …).
//   The route passes req.db (the Sequelize instance for the logged-in company)
//   and this function returns the correct model for that database.
//   db.isDefined() check prevents "model already defined" errors when the same
//   company's model is initialised more than once during a request cycle.
// ─────────────────────────────────────────────────────────────────────────────
const { DataTypes } = require('sequelize');

/**
 * defineLocation(db)
 * Returns the Sequelize model for mLocation in the given company database.
 *
 * @param {import('sequelize').Sequelize} db  - company Sequelize instance (req.db)
 * @returns {import('sequelize').ModelStatic}
 */
function defineLocation(db) {
  // Return cached model if already defined for this db instance
  if (db.isDefined('mLocation')) return db.model('mLocation');

  return db.define(
    'mLocation',
    {
      // ── Primary Key ──────────────────────────────────────────────────────
      pkLocationID: {
        type:       DataTypes.STRING(100),
        primaryKey: true,
        comment:    'UUID v4 generated by randomUUID()',
      },

      // ── Group / Branch scope ─────────────────────────────────────────────
      // fkGroupID scopes this record to one company group (e.g. BHW).
      // All companies in the group share the same location list because
      // they share the same physical godowns.
      fkGroupID: {
        type:    DataTypes.STRING(10),
        allowNull: false,
      },
      fkBranchID: {
        type:    DataTypes.STRING(10),
        allowNull: false,
      },

      // ── Godown reference ─────────────────────────────────────────────────
      // Which godown this location belongs to.
      // Stored as UUID (pkGodownID from mGodown table).
      // The frontend resolves this to a display name (gNum) for the user.
      fkGodownID: {
        type:    DataTypes.STRING(100),
        allowNull: false,
        comment: 'pkGodownID from mGodown — which godown contains this location',
      },

      // ── Location details ─────────────────────────────────────────────────
      // LocationCode: short identifier used on physical labels and reports.
      // Example values: L1, L2, A-ROW, FRONT, BACK, SHELF-3
      LocationCode: {
        type:    DataTypes.STRING(10),
        allowNull: false,
        comment: 'Short code printed on lot cards e.g. L1, FRONT',
      },

      // LocationName: full descriptive name shown in dropdowns and reports.
      // Example: "Left Side Row 1", "Front Bay", "Mezzanine Level"
      LocationName: {
        type:    DataTypes.STRING(50),
        allowNull: false,
        comment: 'Full descriptive name of the location',
      },

      // ── Area ─────────────────────────────────────────────────────────────
      lsqrft: {
        type:    DataTypes.DECIMAL(5, 2),
        allowNull: true,
        comment: 'Floor area of the location in square feet',
      },

      // ── Optional note ────────────────────────────────────────────────────
      lNote: {
        type: DataTypes.TEXT,
        allowNull: true,
      },

      // ── Soft delete flag ─────────────────────────────────────────────────
      // 'Y' = active (visible in dropdowns), 'N' = deactivated.
      // Records are never hard-deleted to preserve historical references.
      Active: {
        type:         DataTypes.STRING(2),
        allowNull:    false,
        defaultValue: 'Y',
      },

      // ── Audit fields ─────────────────────────────────────────────────────
      fkUserID: {
        type:    DataTypes.STRING(100),
        allowNull: false,
        comment: 'pkUserId of the user who last created / modified this record',
      },
      CrMod: {
        type:    DataTypes.DATE,
        allowNull: false,
        comment: 'Timestamp of last create or modify',
      },
    },
    {
      tableName:       'mLocation',
      timestamps:      false,   // CrMod is managed manually
      freezeTableName: true,
    }
  );
}

module.exports = defineLocation;
